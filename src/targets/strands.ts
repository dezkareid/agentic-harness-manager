import path from 'node:path';
import { TARGET_DEFAULT_STRATEGY } from '../config/resolve.js';
import { skillNameSchema } from '../core/frontmatter.js';
import { writeGenerated } from '../strategies/index.js';
import { writeFlattenedContext } from './context.js';
import { hooksOf } from './hooks.js';
import { applyStrategy, bodyOf } from './shared.js';
import type { ExportedItem, Target, TargetOutput } from './types.js';

export const STRANDS_CONTEXT_LIMIT = 16 * 1024;
export const STRANDS_STUB = 'ahm.strands.py';

/** Claude hook events with a Strands equivalent. */
const STRANDS_EVENTS = ['PreToolUse', 'PostToolUse'] as const;

interface HookCommand {
  matcher: string;
  command: string;
}

interface MatcherGroup {
  matcher?: string;
  hooks?: Array<{ type?: string; command?: string }>;
}

/** JSON string escapes are valid Python string escapes. */
const py = (value: string): string => JSON.stringify(value);

const pythonIdentifier = (name: string): string => {
  const identifier = name.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(identifier) ? `agent_${identifier}` : identifier;
};

export const collectHookCommands = (
  merged: ExportedItem[],
): { commands: Record<string, HookCommand[]>; dropped: Array<{ name: string; reason: string }> } => {
  const commands: Record<string, HookCommand[]> = { PreToolUse: [], PostToolUse: [] };
  const dropped: Array<{ name: string; reason: string }> = [];
  for (const { item } of merged.filter(entry => entry.item.kind === 'hook')) {
    for (const [event, groups] of Object.entries(hooksOf(item))) {
      if (!(STRANDS_EVENTS as readonly string[]).includes(event)) {
        dropped.push({ name: item.name, reason: `event ${event} not supported by strands` });
        continue;
      }
      for (const group of groups as MatcherGroup[]) {
        for (const handler of group.hooks ?? []) {
          if (handler.type !== 'command' || !handler.command) {
            dropped.push({ name: item.name, reason: `${event}: handler type ${handler.type ?? '(none)'} not supported by strands` });
            continue;
          }
          commands[event].push({ matcher: group.matcher ?? '', command: handler.command });
        }
      }
    }
  }
  return { commands, dropped };
};

const renderHookCommands = (commands: Record<string, HookCommand[]>): string => {
  const events = Object.entries(commands).map(([event, list]) => {
    const entries = list.map(({ matcher, command }) => `        {"matcher": ${py(matcher)}, "command": ${py(command)}},\n`).join('');
    return `    ${py(event)}: [\n${entries}    ],\n`;
  });
  return `HOOK_COMMANDS: dict[str, list[dict[str, str]]] = {\n${events.join('')}}\n`;
};

const renderAgents = (agents: ExportedItem[]): string => {
  const names: string[] = [];
  const blocks = agents.map(({ item, settings }) => {
    const identifier = pythonIdentifier(item.name);
    names.push(identifier);
    return [
      `${identifier} = Agent(`,
      `    name=${py(item.name)},`,
      `    description=${py(String(item.frontmatter?.description ?? ''))},`,
      `    system_prompt=${py(bodyOf(item, settings))},`,
      ').as_tool()',
      '',
    ].join('\n');
  });
  return `${blocks.join('\n')}\nAGENT_TOOLS = [${names.join(', ')}]\n`;
};

/** Generates the Python stub that wires harness hooks and subagents into a Strands agent. */
export const renderStrandsStub = (commands: Record<string, HookCommand[]>, agents: ExportedItem[]): string => `# Generated by ahm (agentic-harness-manager) from the harness hooks and agents.
# Regenerate with \`ahm export --target strands --force\`; local edits are overwritten.
#
# Usage:
#   from ahm_strands import AhmHooks, AGENT_TOOLS
#   agent = Agent(hooks=[AhmHooks()], tools=[*AGENT_TOOLS])
import re
import subprocess
from typing import Any

from strands import Agent
from strands.hooks import AfterToolCallEvent, BeforeToolCallEvent, HookProvider, HookRegistry

${renderHookCommands(commands)}

def _run_hooks(event: str, tool_name: str) -> None:
    for hook in HOOK_COMMANDS.get(event, []):
        matcher = hook["matcher"]
        if matcher not in ("", "*") and not re.fullmatch(matcher, tool_name):
            continue
        subprocess.run(hook["command"], shell=True, check=False)


class AhmHooks(HookProvider):
    """Runs the harness PreToolUse/PostToolUse commands around Strands tool calls."""

    def register_hooks(self, registry: HookRegistry, **kwargs: Any) -> None:
        registry.add_callback(BeforeToolCallEvent, self.before_tool_call)
        registry.add_callback(AfterToolCallEvent, self.after_tool_call)

    def before_tool_call(self, event: BeforeToolCallEvent) -> None:
        _run_hooks("PreToolUse", event.tool_use["name"])

    def after_tool_call(self, event: AfterToolCallEvent) -> None:
        _run_hooks("PostToolUse", event.tool_use["name"])


${renderAgents(agents)}`;

/**
 * Strands: skills copied to `.agent/skills/<name>/` (the harness default scan dir, singular),
 * a flattened `AGENTS.md`, and hooks plus subagents generated as code in `ahm.strands.py`.
 */
export const strandsTarget: Target = {
  id: 'strands',
  defaultStrategy: TARGET_DEFAULT_STRATEGY.strands,
  supports: () => true,
  layout: (item) => {
    switch (item.kind) {
      case 'skill':
        return { destPath: path.join('.agent', 'skills', item.name), mode: 'dir' };
      case 'context':
        return { destPath: item.name, mode: 'file' };
      case 'hook':
      case 'agent':
        return { destPath: STRANDS_STUB, mode: 'merge' };
    }
  },
  transform: async (item, dest, ctx) => {
    if (item.kind === 'context') {
      return writeFlattenedContext(item, dest, ctx, STRANDS_CONTEXT_LIMIT);
    }
    if (item.kind === 'skill' && !skillNameSchema.safeParse(item.name).success) {
      return [{ dest, action: 'skipped', reason: 'skill name must be lowercase letters, numbers and hyphens (≤ 64)' }];
    }
    return applyStrategy(item, dest, ctx);
  },
  postProcess: async (ctx) => {
    if (ctx.merged.length === 0) {
      return [];
    }
    const file = path.join(ctx.outputDir, STRANDS_STUB);
    const { commands, dropped } = collectHookCommands(ctx.merged);
    const agents = ctx.merged.filter(entry => entry.item.kind === 'agent');
    const result = await writeGenerated(file, renderStrandsStub(commands, agents), ctx.strategy);
    const skipped: TargetOutput[] = dropped.map(({ name, reason }) => ({ dest: file, kind: 'hook', name, action: 'skipped', reason }));
    return [{ dest: file, ...result }, ...skipped];
  },
};
